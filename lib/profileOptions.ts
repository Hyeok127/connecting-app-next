// 저장 형식: 시/도만이면 "서울", 하위까지면 "서울 강남구"(공백 구분).
export function regionValue(sido: string, sub?: string): string {
  return sub ? `${sido} ${sub}` : sido;
}

// 선호 지역 r이 상대 지역 region을 커버하는지.
//   "서울"   → "서울", "서울 강남구" 모두 매칭(시/도 전체)
//   "서울 강남구" → "서울 강남구"만 매칭(구 단위)
export function regionCovers(prefRegion: string, region: string): boolean {
  if (!region) return false;
  return region === prefRegion || region.startsWith(prefRegion + " ");
}
